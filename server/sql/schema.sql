-- =============================================================================
-- Community Food Wastage Reduction Portal
-- PostgreSQL / Neon schema (PostgreSQL 13+)
--
-- Run with:
--   npm run db:create      (uses DATABASE_URL from server/.env)
--   psql "$DATABASE_URL" -f server/sql/schema.sql
--
-- The script is idempotent: it drops and recreates every object, so it can be
-- re-run at any time against a development database.
--
-- Design notes
--  * Every table is normalised to 3NF; no repeating groups.
--  * Location is stored as NUMERIC(10,7) lat/lng so the API can run a
--    bounding-box + haversine radius search entirely in SQL.
--  * status / best_before / location are indexed because the recipient feed
--    filters on exactly those columns (status = 'AVAILABLE', not expired,
--    within radius).
--  * claims has a UNIQUE constraint on donation_id. This is the second layer of
--    protection (after the SELECT ... FOR UPDATE row lock) that makes it
--    impossible for two recipients to claim the same donation.
--  * MySQL ENUMs became VARCHAR + CHECK constraints, and JSON became JSONB.
--    `updated_at` is maintained by a trigger (Postgres has no ON UPDATE clause).
-- =============================================================================

-- Drop in dependency-safe order (CASCADE handles the foreign keys) so the
-- script is re-runnable.
DROP TABLE IF EXISTS feedback CASCADE;
DROP TABLE IF EXISTS notifications CASCADE;
DROP TABLE IF EXISTS status_history CASCADE;
DROP TABLE IF EXISTS claims CASCADE;
DROP TABLE IF EXISTS donation_images CASCADE;
DROP TABLE IF EXISTS donations CASCADE;
DROP TABLE IF EXISTS food_categories CASCADE;
DROP TABLE IF EXISTS ngo_verifications CASCADE;
DROP TABLE IF EXISTS users CASCADE;

-- -----------------------------------------------------------------------------
-- updated_at trigger helper (replaces MySQL's ON UPDATE CURRENT_TIMESTAMP)
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- -----------------------------------------------------------------------------
-- users
-- One row per human account. `role` drives role based access control (RBAC).
-- `account_status` is how the admin gate-keeps NGOs/shelters:
--   * DONOR      -> ACTIVE immediately (individuals, restaurants, hotels)
--   * RECIPIENT  -> ACTIVE for volunteers, PENDING_VERIFICATION for NGOs/shelters
--   * ADMIN      -> created by seed / other admin only
-- -----------------------------------------------------------------------------
CREATE TABLE users (
  id              INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email           VARCHAR(255) NOT NULL,
  password_hash   VARCHAR(255) NOT NULL,
  full_name       VARCHAR(150) NOT NULL,
  phone           VARCHAR(30)  NULL,
  city            VARCHAR(100) NULL,
  address         VARCHAR(255) NULL,
  -- Home / organisation coordinates. Captured from the browser geolocation or
  -- the map pin picker. Used to find NGOs near a newly posted donation.
  latitude        NUMERIC(10,7) NULL,
  longitude       NUMERIC(10,7) NULL,
  -- 'NGO' | 'SHELTER' | 'VOLUNTEER' | 'RESTAURANT' | 'HOTEL' | 'INDIVIDUAL'
  -- Kept as a free-form label so the three top-level roles stay simple.
  org_type        VARCHAR(40)  NULL,
  avatar_url      VARCHAR(500) NULL,
  role            VARCHAR(20)  NOT NULL DEFAULT 'DONOR'
                    CHECK (role IN ('DONOR','RECIPIENT','ADMIN')),
  account_status  VARCHAR(30)  NOT NULL DEFAULT 'ACTIVE'
                    CHECK (account_status IN ('PENDING_VERIFICATION','ACTIVE','SUSPENDED')),
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Emails are unique case-insensitively (MySQL achieved this with a *_ci
-- collation; Postgres needs a functional index plus lower() comparisons).
CREATE UNIQUE INDEX uq_users_email ON users (lower(email));
CREATE INDEX idx_users_role     ON users (role);
CREATE INDEX idx_users_status   ON users (account_status);
CREATE INDEX idx_users_city     ON users (city);
CREATE INDEX idx_users_location ON users (latitude, longitude);

CREATE TRIGGER trg_users_updated_at
  BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- -----------------------------------------------------------------------------
-- ngo_verifications
-- One verification record per NGO/shelter recipient. The uploaded proof
-- (registration certificate, 80G, GST, trust deed...) lives on disk (Multer)
-- or in Firebase Storage and we only persist the URL/path here.
-- -----------------------------------------------------------------------------
CREATE TABLE ngo_verifications (
  id             INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        INTEGER      NOT NULL,
  document_type  VARCHAR(80)  NOT NULL,          -- e.g. 'REGISTRATION_CERTIFICATE'
  document_url   VARCHAR(500) NOT NULL,          -- '/uploads/verifications/xxx.pdf'
  status         VARCHAR(20)  NOT NULL DEFAULT 'PENDING'
                   CHECK (status IN ('PENDING','APPROVED','REJECTED')),
  review_note    VARCHAR(500) NULL,              -- reason for approval / rejection
  reviewed_by    INTEGER      NULL,              -- admin user id
  submitted_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
  reviewed_at    TIMESTAMPTZ  NULL,
  CONSTRAINT uq_verification_user UNIQUE (user_id),  -- one active verification per user
  CONSTRAINT fk_verification_user
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_verification_reviewer
    FOREIGN KEY (reviewed_by) REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX idx_verification_status ON ngo_verifications (status);

-- -----------------------------------------------------------------------------
-- food_categories
-- Admin managed. `type` mirrors the Veg / Non-Veg filter used on the map.
-- -----------------------------------------------------------------------------
CREATE TABLE food_categories (
  id          INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(100) NOT NULL,
  slug        VARCHAR(100) NOT NULL,
  type        VARCHAR(10)  NOT NULL DEFAULT 'VEG' CHECK (type IN ('VEG','NON_VEG')),
  -- 1 / 0 (kept numeric so the API keeps emitting 1/0 like MySQL's TINYINT(1))
  is_active   SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT uq_category_name UNIQUE (name),
  CONSTRAINT uq_category_slug UNIQUE (slug)
);

CREATE INDEX idx_category_active ON food_categories (is_active);

-- -----------------------------------------------------------------------------
-- donations
-- A surplus food listing. Lifecycle: AVAILABLE -> CLAIMED -> DELIVERED.
-- CANCELLED is a terminal state a donor can reach while still AVAILABLE.
-- -----------------------------------------------------------------------------
CREATE TABLE donations (
  id                INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  donor_id          INTEGER      NOT NULL,
  category_id       INTEGER      NOT NULL,
  title             VARCHAR(200) NOT NULL,
  description       TEXT         NULL,
  quantity_kg       NUMERIC(8,2) NULL,           -- filled when unit = 'kg'
  quantity_servings INTEGER      NULL,           -- filled when unit = 'servings'
  unit              VARCHAR(10)  NOT NULL DEFAULT 'kg' CHECK (unit IN ('kg','servings')),
  best_before       TIMESTAMPTZ  NOT NULL,       -- listings past this are hidden
  pickup_address    VARCHAR(255) NULL,
  pickup_city       VARCHAR(100) NOT NULL,
  pickup_latitude   NUMERIC(10,7) NOT NULL,
  pickup_longitude  NUMERIC(10,7) NOT NULL,
  status            VARCHAR(20)  NOT NULL DEFAULT 'AVAILABLE'
                      CHECK (status IN ('AVAILABLE','CLAIMED','DELIVERED','CANCELLED')),
  created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT fk_donation_donor
    FOREIGN KEY (donor_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_donation_category
    FOREIGN KEY (category_id) REFERENCES food_categories(id)
);

CREATE INDEX idx_donation_status   ON donations (status);              -- feed filter
CREATE INDEX idx_donation_expiry   ON donations (best_before);         -- hide expired
CREATE INDEX idx_donation_city     ON donations (pickup_city);         -- city filter
CREATE INDEX idx_donation_location ON donations (pickup_latitude, pickup_longitude);
CREATE INDEX idx_donation_donor    ON donations (donor_id, status);

CREATE TRIGGER trg_donations_updated_at
  BEFORE UPDATE ON donations
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- -----------------------------------------------------------------------------
-- donation_images
-- Many photos per listing.
-- -----------------------------------------------------------------------------
CREATE TABLE donation_images (
  id           INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  donation_id  INTEGER      NOT NULL,
  image_url    VARCHAR(500) NOT NULL,
  is_primary   SMALLINT     NOT NULL DEFAULT 0 CHECK (is_primary IN (0, 1)),
  created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT fk_image_donation
    FOREIGN KEY (donation_id) REFERENCES donations(id) ON DELETE CASCADE
);

CREATE INDEX idx_image_donation ON donation_images (donation_id);

-- -----------------------------------------------------------------------------
-- claims
-- A recipient's claim on a donation. UNIQUE(donation_id) is what makes
-- double-claiming impossible even under concurrent requests.
-- -----------------------------------------------------------------------------
CREATE TABLE claims (
  id                  INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  donation_id         INTEGER      NOT NULL,
  recipient_id        INTEGER      NOT NULL,
  status              VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE'
                        CHECK (status IN ('ACTIVE','DELIVERED','CANCELLED')),
  pickup_note         VARCHAR(500) NULL,
  claimed_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
  delivered_at        TIMESTAMPTZ  NULL,
  delivered_proof_url VARCHAR(500) NULL,
  CONSTRAINT uq_claim_donation UNIQUE (donation_id),   -- only one claim per donation
  CONSTRAINT fk_claim_donation
    FOREIGN KEY (donation_id) REFERENCES donations(id) ON DELETE CASCADE,
  CONSTRAINT fk_claim_recipient
    FOREIGN KEY (recipient_id) REFERENCES users(id)
);

CREATE INDEX idx_claim_recipient ON claims (recipient_id, status);
CREATE INDEX idx_claim_status    ON claims (status);

-- -----------------------------------------------------------------------------
-- status_history
-- Append-only audit trail of every status change (Available -> Claimed ->
-- Delivered) with who did it and when.
-- -----------------------------------------------------------------------------
CREATE TABLE status_history (
  id           INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  donation_id  INTEGER      NOT NULL,
  status       VARCHAR(20)  NOT NULL
                 CHECK (status IN ('AVAILABLE','CLAIMED','DELIVERED','CANCELLED')),
  changed_by   INTEGER      NOT NULL,
  note         VARCHAR(500) NULL,
  changed_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT fk_history_donation
    FOREIGN KEY (donation_id) REFERENCES donations(id) ON DELETE CASCADE,
  CONSTRAINT fk_history_user
    FOREIGN KEY (changed_by) REFERENCES users(id)
);

CREATE INDEX idx_history_donation ON status_history (donation_id, changed_at);

-- -----------------------------------------------------------------------------
-- notifications
-- In-app dashboard notifications. The client polls /api/notifications/unread-count
-- every 30s for the badge; read_at IS NULL means unread.
-- `payload` is a JSONB blob holding deep-link info, e.g. {"donationId": 12}.
-- -----------------------------------------------------------------------------
CREATE TABLE notifications (
  id         INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER      NOT NULL,
  type       VARCHAR(60)  NOT NULL,  -- DONATION_POSTED | CLAIM_CREATED | DELIVERED | ...
  title      VARCHAR(200) NOT NULL,
  message    VARCHAR(500) NOT NULL,
  payload    JSONB        NULL,
  read_at    TIMESTAMPTZ  NULL,
  created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT fk_notification_user
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX idx_notification_user    ON notifications (user_id, read_at);  -- unread badge
CREATE INDEX idx_notification_created ON notifications (created_at);

-- -----------------------------------------------------------------------------
-- feedback
-- Recipient's 1-5 star rating + hygiene comment for a DELIVERED donation.
-- The donor's average rating is computed with AVG(feedback.rating).
-- -----------------------------------------------------------------------------
CREATE TABLE feedback (
  id            INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  donation_id   INTEGER      NOT NULL,
  recipient_id  INTEGER      NOT NULL,
  donor_id      INTEGER      NOT NULL,           -- denormalised for fast Avg(donor)
  rating        SMALLINT     NOT NULL,
  comment       TEXT         NULL,
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT uq_feedback_donation UNIQUE (donation_id),  -- one review per donation
  CONSTRAINT fk_feedback_donation
    FOREIGN KEY (donation_id) REFERENCES donations(id) ON DELETE CASCADE,
  CONSTRAINT fk_feedback_recipient
    FOREIGN KEY (recipient_id) REFERENCES users(id),
  CONSTRAINT fk_feedback_donor
    FOREIGN KEY (donor_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT chk_feedback_rating CHECK (rating BETWEEN 1 AND 5)
);

CREATE INDEX idx_feedback_donor ON feedback (donor_id);
